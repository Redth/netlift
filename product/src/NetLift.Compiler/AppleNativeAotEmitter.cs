            {
                throw new ContractCompilerException(
                    $"Apple service implementation for '{service.Name}' was not provided.");
            }
            if (implementation.NativeServiceDependencies.Count != 0)
            {
                throw new ContractCompilerException(
                    $"Apple NativeAOT does not support managed-to-native callbacks required by '{implementation.Implementation}'.");
            }
            constructorCalls.Add($"new global::{implementation.Implementation}()");
